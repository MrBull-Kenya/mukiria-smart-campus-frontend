// NOTIFICATIONS (the bell in the top bar). Computed from live data on request, so there is nothing to store or clean up.
// Ids are stable while the situation is unchanged (and change when it does, e.g. "3 waiting" -> "4 waiting"), which is
// how the app knows what is new. "Read" state lives in the user's own browser.
