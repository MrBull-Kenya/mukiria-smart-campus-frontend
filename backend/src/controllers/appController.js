// Wrap every handler so a thrown error becomes a clean JSON 500 (details only in the server log)
export const wrap = (fn) => async (req, res) => {
  try { await fn(req, res); } catch (err) { console.error(`${req.method} ${req.originalUrl} failed:`, err); res.status(500).json({ error: 'Something went wrong on the server.' }); }
};
const bad = (res, msg, code = 400) => res.status(code).json({ error: msg });

// ---------- timetable files: ANY file type up to 10 MB, stored privately ----------
// Files live in backend/storage/timetables (NOT in the publicly served /uploads folder) and are only handed out by
// sendTimetableFile() to signed-in users who may see them. Only PDF and common image types open in the browser;
// everything else (including HTML/SVG, which can run scripts) is forced to download, with nosniff.
export const MAX_TIMETABLE_BYTES = 10 * 1024 * 1024;
const PREVIEW_TYPES = { pdf: 'application/pdf', png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', gif: 'image/gif', webp: 'image/webp' };
const PREVIEWABLE = new Set(Object.values(PREVIEW_TYPES));
const safeExt = (name) => path.extname(String(name || '')).slice(1).toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 10);
const cleanName = (name) => path.basename(String(name || 'timetable').replace(/\\/g, '/')).replace(/[\u0000-\u001f"]/g, '').trim().slice(0, 200) || 'timetable';
const fileInfo = (v) => (v.file_path ? { name: v.file_name, type: v.file_type, size: v.file_size, previewable: PREVIEWABLE.has(v.file_type) } : null);

export const timetableUpload = multer({
  storage: multer.diskStorage({
    destination: (req, file, cb) => { fs.mkdirSync(TIMETABLE_DIR, { recursive: true }); cb(null, TIMETABLE_DIR); },
    // the stored name is generated by the server, so a hostile original filename can never choose where the file goes
    filename: (req, file, cb) => { const ext = safeExt(file.originalname); cb(null, `${crypto.randomUUID()}${ext ? `.${ext}` : ''}`); },
  }),
  limits: { fileSize: MAX_TIMETABLE_BYTES, files: 1 },
});

// GET .../:id/file  (rep: own class only; HOD/admin: any)   ?download=1 forces a download
export const sendTimetableFile = wrap(async (req, res) => {
  const v = await one('SELECT * FROM timetable_versions WHERE id = ?', [req.params.id]);
  if (!v || !v.file_path) return bad(res, 'This timetable has no file attached.', 404);
  if (['student', 'student_rep'].includes(req.user.role) && v.class_code !== req.user.class_code) return bad(res, "That isn't your class's timetable.", 403);
  if (req.user.role === 'student' && v.status !== 'approved') return bad(res, 'Students can only view approved timetables.', 403);
  const full = path.join(TIMETABLE_DIR, path.basename(v.file_path));
  if (!fs.existsSync(full)) return bad(res, 'The stored file is missing from the server.', 404);

  const inline = !req.query.download && PREVIEWABLE.has(v.file_type);
  const ascii = v.file_name.replace(/[^\x20-\x7e]/g, '_');
  res.setHeader('Content-Type', inline ? v.file_type : 'application/octet-stream');
  res.setHeader('Content-Disposition', `${inline ? 'inline' : 'attachment'}; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(v.file_name)}`);
  res.setHeader('Content-Length', fs.statSync(full).size);
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('Cache-Control', 'private, no-store');
  fs.createReadStream(full).pipe(res);
});


