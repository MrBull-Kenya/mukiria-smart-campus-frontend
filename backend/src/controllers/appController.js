const daysAgo = (n) => new Date(Date.now() - n * 86400000);
const KIND_ORDER = { warn: 0, ok: 1, info: 2 };

export const notifications = wrap(async (req, res) => {
  const role = req.user.role, items = [];
  const add = (id, kind, icon, title, text, link, when) => items.push({ id, kind, icon, title, text, link, when: when ? `${fmtDate(when)} ${fmtTime(when)}` : null });
  const count = async (sql, params = []) => (await one(sql, params)).n;
  const weekend = (() => { const d = new Date().getDay(); return d === 5 || d === 6 || d === 0; })(); // Friday to Sunday

  if (role === 'student' || role === 'student_rep') {
    const st = await me(req);
    if (st) {
      const live = await one('SELECT id, unit_name FROM sessions WHERE class_code = ? AND is_active = 1 ORDER BY id DESC LIMIT 1', [st.class_code]);
      if (live && !(await one('SELECT id FROM attendance_logs WHERE session_id = ? AND adm_no = ?', [live.id, st.adm_no]))) add(`open-${live.id}`, 'warn', '📷', `Attendance is open: ${live.unit_name}`, 'Scan the class QR code to check in.', '/scan');
      const pct = Number(st.attendance_pct);
      if ((await sessionsHeld(st.class_code)) > 0 && pct < T) add(`low-${Math.floor(pct)}`, 'warn', '⚠️', `Your attendance is ${pct.toFixed(1)}%`, `You need at least ${T}% to sit exams.`, '/student/exam-eligibility');
      for (const a of await q('SELECT id, message, created_at FROM chat_messages WHERE class_code = ? AND is_announcement = 1 AND created_at >= ? ORDER BY id DESC LIMIT 5', [st.class_code, sqlDate(daysAgo(7))])) add(`ann-${a.id}`, 'info', '📢', 'Class announcement', a.message, '/student/chat', a.created_at);
      for (const t of await q("SELECT id, status, created_at FROM temp_id_requests WHERE adm_no = ? AND status IN ('approved', 'rejected') AND created_at >= ? ORDER BY id DESC LIMIT 3", [st.adm_no, sqlDate(daysAgo(7))])) add(`tid-${t.id}-${t.status}`, t.status === 'approved' ? 'ok' : 'warn', '🪪', `Your temporary ID was ${t.status}`, t.status === 'approved' ? 'It is valid for 24 hours.' : 'Ask your class rep if you still need one.', '/student/request-temp-id', t.created_at);
      if (role === 'student_rep') {
        const waiting = await count("SELECT COUNT(*) AS n FROM temp_id_requests t JOIN students s ON s.adm_no = t.adm_no JOIN users u ON u.id = s.user_id WHERE u.class_code = ? AND t.status = 'pending'", [st.class_code]);
        if (waiting) add(`rep-tid-${waiting}`, 'warn', '🪪', `${waiting} temporary ID request${waiting > 1 ? 's' : ''} waiting`, 'Students in your class are waiting for you to approve.', '/rep/temp-ids');
        const tt = await one("SELECT id, status, term, hod_comment FROM timetable_versions WHERE class_code = ? AND status IN ('approved', 'rejected') AND created_at >= ? ORDER BY id DESC LIMIT 1", [st.class_code, sqlDate(daysAgo(14))]);
        if (tt) add(`tt-${tt.id}-${tt.status}`, tt.status === 'approved' ? 'ok' : 'warn', '🗓️', `Your timetable was ${tt.status}`, tt.status === 'rejected' && tt.hod_comment ? `HOD: ${tt.hod_comment}` : tt.term, '/rep/timetable');
        if (weekend) add(`weekly-${isoDay(weekBounds('').mon)}`, 'info', '🖨️', "Print this week's attendance register", 'Download it, print it, and get it signed.', '/rep/weekly-sheet');
      }
    }
  } else if (role === 'teacher') {
    const waiting = (await lecturerSessions(req)).filter((s) => !s.signed_at && !s.is_active).length;
    if (waiting) add(`sign-${waiting}`, 'warn', '✍️', `${waiting} lesson${waiting > 1 ? 's' : ''} waiting for your signature`, 'Confirm the class register for each lesson.', '/teacher/sign-attendance');
  } else if (role === 'hod' || role === 'admin') {
    if (role === 'hod') {
      const reps = await count("SELECT COUNT(*) AS n FROM users WHERE role = 'student_rep' AND status = 'pending'");
      if (reps) add(`reps-${reps}`, 'warn', '✅', `${reps} class rep${reps > 1 ? 's' : ''} awaiting approval`, 'They cannot sign in until you approve them.', '/hod/approve-rep');
      const tts = await count("SELECT COUNT(*) AS n FROM timetable_versions WHERE status = 'pending'");
      if (tts) add(`tts-${tts}`, 'warn', '🗓️', `${tts} timetable${tts > 1 ? 's' : ''} awaiting approval`, 'Open the file and approve or reject it.', '/hod/timetables');
      const risk = (await allStudentsWithStats()).filter((s) => s.attendance < T).length;
      if (risk) add(`risk-${risk}`, 'info', '⚠️', `${risk} student${risk > 1 ? 's' : ''} below ${T}% attendance`, 'They are at risk of being barred from exams.', '/hod/at-risk');
    } else {
      const staff = await count("SELECT COUNT(*) AS n FROM users WHERE role IN ('teacher', 'hod', 'admin') AND status = 'pending'");
      if (staff) add(`staff-${staff}`, 'warn', '👥', `${staff} staff registration${staff > 1 ? 's' : ''} awaiting approval`, 'Approve or reject them.', '/admin/staff');
      if (!isEmailConfigured()) add('email-unset', 'warn', '📧', "Email isn't set up", 'Nobody can reset a forgotten password by email until it is.', '/admin/settings');
      if (!(await one("SELECT setting_value FROM app_settings WHERE setting_key = 'term_start'"))) add('term-unset', 'info', '⚙️', 'Term start date not set', 'Printed registers will have a blank WEEK number.', '/admin/settings');
    }
  }
  items.sort((a, b) => KIND_ORDER[a.kind] - KIND_ORDER[b.kind]);
  res.json({ items: items.slice(0, 20) });
});
